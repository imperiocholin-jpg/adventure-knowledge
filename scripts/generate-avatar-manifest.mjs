/**
 * 根据 public/image/avatars 下文件名（boy-*.png / girl-*.png）生成头像 ID 列表。
 * 运行：node scripts/generate-avatar-manifest.mjs
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const avatarsDir = path.join(root, "public", "image", "avatars")
const outFile = path.join(root, "lib", "user", "avatar-ids.generated.ts")

const avatarIdPattern = /^(boy|girl)-\d{2}$/i

function sortIds(a, b) {
  const order = (id) => (id.startsWith("boy-") ? 0 : 1)
  const diff = order(a) - order(b)
  if (diff !== 0) return diff
  return a.localeCompare(b)
}

const files = fs
  .readdirSync(avatarsDir)
  .filter((name) => name.toLowerCase().endsWith(".png"))
  .map((name) => name.replace(/\.png$/i, ""))
  .filter((id) => avatarIdPattern.test(id))
  .sort(sortIds)

if (files.length === 0) {
  console.error("No boy-*.png / girl-*.png files found in", avatarsDir)
  process.exit(1)
}

const content = `// AUTO-GENERATED by scripts/generate-avatar-manifest.mjs — do not edit manually
export const AVATAR_IDS = ${JSON.stringify(files, null, 2)} as const

export type AvatarId = (typeof AVATAR_IDS)[number]
`

fs.writeFileSync(outFile, content, "utf8")
console.log(`Wrote ${files.length} avatar ids to ${path.relative(root, outFile)}`)
